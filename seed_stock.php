// Ensure tables exist
$conn->query("CREATE TABLE IF NOT EXISTS stock_items (
    id INT AUTO_INCREMENT PRIMARY KEY,
    item_code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    unit VARCHAR(50) DEFAULT 'ชิ้น',
    price_per_unit DECIMAL(10,2) DEFAULT 0,
    min_stock INT DEFAULT 0,
    max_stock INT DEFAULT 0,
    type ENUM('stationery','maid') NOT NULL DEFAULT 'stationery',
    company ENUM('PTA','PT4','PTE') NOT NULL DEFAULT 'PTA',
    is_active TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_item_code_company (item_code, company)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");

$inserted = 0; $skipped = 0; $errors = [];

function ins($conn, $code, $name, $unit, $price, $min, $max, $type, $company) {
    global $inserted, $skipped, $errors;
    $stmt = $conn->prepare("INSERT IGNORE INTO stock_items (item_code,name,unit,price_per_unit,min_stock,max_stock,type,company,is_active) VALUES(?,?,?,?,?,?,?,?,1)");
    $stmt->bind_param("sssdiiss", $code, $name, $unit, $price, $min, $max, $type, $company);
    if ($stmt->execute()) {
        if ($stmt->affected_rows > 0) $inserted++;
        else $skipped++;
    } else {
        $errors[] = "$code/$company: " . $stmt->error;
    }
}

